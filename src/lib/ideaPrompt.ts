/**
 * 이번 딸깍용 사용자 프롬프트를 조립한다.
 *
 * @param seed rollIdeaSeed()로 뽑은 랜덤 조합
 * @param recentTitles 최근 생성된 아이디어 제목 (중복 회피용)
 * @param focus 추가 방향 (MCP 배치용 선택값 — 앱 딸깍은 넘기지 않는다)
 */
export function buildIdeaUserPrompt(seed: IdeaSeed, recentTitles: string[], focus?: string): string {
  const avoidance =
    recentTitles.length > 0
      ? `\n\n## 이미 나온 아이디어 (같은 방향·같은 소재는 피하십시오)\n${recentTitles
          .slice(0, 15)
          .map((t) => `- ${t}`)
          .join('\n')}`
      : ''

  const direction = focus && focus.trim()
    ? `\n\n## 추가 방향 (반드시 반영하되, 재료와 충돌하면 이 방향을 우선하십시오)\n${focus.trim()}`
    : ''

  return `아래 랜덤 재료를 **재료로만** 써서 게임 코어 로직 하나를 뽑아주십시오. 재료를 그대로 나열하는 게 아니라, 재료들이 충돌하는 지점에서 새로운 것을 찾으십시오. 재료 중 하나는 버려도 됩니다.

## 이번 재료
- 영감 소재 A: ${seed.inspirations[0]}
- 영감 소재 B: ${seed.inspirations[1]}
- 건드릴 심리: ${seed.hook}
- 비틀기 방식: ${seed.twist}
- 그릇(포맷): ${seed.format}${direction}${avoidance}

JSON 하나만 출력하십시오.`
}

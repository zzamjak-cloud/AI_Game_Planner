function pickRandom<T>(pool: readonly T[]): T {
  return pool[Math.floor(Math.random() * pool.length)]
}

// 서로 다른 항목 n개를 랜덤 추출
function pickDistinct<T>(pool: readonly T[], count: number): T[] {
  const shuffled = [...pool].sort(() => Math.random() - 0.5)
  return shuffled.slice(0, count)
}

export interface IdeaSeed {
  inspirations: string[]
  hook: string
  twist: string
  format: string
  // 사이드바 등 짧게 보여줄 때 쓰는 요약 문자열
  summary: string
}

/**
 * 이번 딸깍에 사용할 랜덤 seed 조합을 뽑는다.
 */
export function rollIdeaSeed(): IdeaSeed {
  const inspirations = pickDistinct(INSPIRATION_SOURCES, 2)
  const hook = pickRandom(PSYCH_HOOKS)
  const twist = pickRandom(TWIST_OPERATORS)
  const format = pickRandom(FORMAT_HINTS)

  // 요약은 소재의 괄호 앞부분만 짧게
  const shortNames = inspirations.map((s) => s.split(' (')[0])
  const summary = `${shortNames.join(' × ')} · ${hook.split(' (')[0]}`

  return { inspirations, hook, twist, format, summary }
}

